_FALLBACK = (0x7F, 0x41, 0x41, 0x41, 0x7F)


def text_width(text: str, scale: int = 1, spacing: int = 1) -> int:
    """字符串渲染宽度：字宽 5 + 字距，乘以缩放。"""
    if not text:
        return 0
    return len(text) * (GLYPH_WIDTH + spacing) * scale - spacing * scale


def fit_text(text: str, max_width: int, scale: int = 1, spacing: int = 1) -> str:
    """超宽时按整字符截断并补 ".."，保证整行标签不越过格子右边界。"""
    if text_width(text, scale, spacing) <= max_width:
        return text
    suffix = ".."
    room = max_width - text_width(suffix, scale, spacing)
    if room < 0:
        return ""
    keep = room // ((GLYPH_WIDTH + spacing) * scale)
    return text[:keep] + suffix


def _fill_block(canvas: bytearray, canvas_width: int, canvas_height: int,
                x: int, y: int, scale: int, color: tuple[int, int, int, int]) -> None:
    if x < 0 or y < 0 or x + scale > canvas_width or y + scale > canvas_height:
        for dy in range(scale):
            yy = y + dy
            if yy < 0 or yy >= canvas_height:
                continue
            for dx in range(scale):
                xx = x + dx
                if 0 <= xx < canvas_width:
                    offset = (yy * canvas_width + xx) * 4
                    canvas[offset:offset + 4] = bytes(color)
        return
    row = bytes(color) * scale
    for dy in range(scale):
        offset = ((y + dy) * canvas_width + x) * 4
        canvas[offset:offset + scale * 4] = row


def draw_text(canvas: bytearray, canvas_width: int, canvas_height: int,
              x: int, y: int, text: str, color: tuple[int, int, int, int] = (230, 233, 239, 255),
              scale: int = 1, spacing: int = 1) -> int:
    """把 text 画到画布的 (x, y)，返回实际占用的宽度；缺少字形时回退大写或方框。"""
    cursor = x
    step = (GLYPH_WIDTH + spacing) * scale
    for char in text:
        glyph = _GLYPHS.get(char)
        if glyph is None:
            glyph = _GLYPHS.get(char.upper(), _FALLBACK)
        for column, bits in enumerate(glyph):
            if not bits:
                continue
            px = cursor + column * scale
            row = 0
            while bits:
                if bits & 1:
                    _fill_block(canvas, canvas_width, canvas_height, px, y + row * scale, scale, color)
                bits >>= 1
                row += 1
        cursor += step
    return cursor - x
